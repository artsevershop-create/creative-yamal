const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const feature = JSON.parse(fs.readFileSync(path.join(root, 'src/data/yamal.geojson'), 'utf8').replace(/^\uFEFF/, ''));
const rad = Math.PI / 180;
const p1 = 64 * rad, p2 = 72 * rad, p0 = 68 * rad, l0 = 74 * rad;
const t = p => Math.tan(Math.PI / 4 + p / 2);
const n = Math.log(Math.cos(p1) / Math.cos(p2)) / Math.log(t(p2) / t(p1));
const f = Math.cos(p1) * t(p1) ** n / n;
const r0 = f / t(p0) ** n;
function project([lon, lat]) { const r = f / t(lat * rad) ** n, theta = n * (lon * rad - l0); return [r * Math.sin(theta), r * Math.cos(theta) - r0]; }
const polygons = feature.geometry.type === 'MultiPolygon' ? feature.geometry.coordinates : [feature.geometry.coordinates];
const all = polygons.flat(2).map(project);
const minX = Math.min(...all.map(p => p[0])), maxX = Math.max(...all.map(p => p[0]));
const minY = Math.min(...all.map(p => p[1])), maxY = Math.max(...all.map(p => p[1]));
const scale = Math.min(640 / (maxX - minX), 640 / (maxY - minY));
const ox = (800 - (maxX - minX) * scale) / 2, oy = (760 - (maxY - minY) * scale) / 2;
function point(coords) { const [x, y] = project(coords); return [+(ox + (x - minX) * scale).toFixed(2), +(oy + (y - minY) * scale).toFixed(2)]; }
function line(coords) { return coords.map((p, i) => `${i ? 'L' : 'M'}${point(p).join(',')}`).join(''); }
const outline = polygons.map(poly => poly.map(ring => line(ring) + 'Z').join('')).join('');
const raw = [
 ['salekhard', 'Салехард', 66.60954661, 66.53372958, -26, 33],
 ['labytnangi', 'Лабытнанги', 66.4183333, 66.6572222, -32, -20],
 ['urengoy', 'Новый Уренгой', 76.6333333, 66.0833333, 18, -16],
 ['noyabrsk', 'Ноябрьск', 75.43728, 63.19309, 16, 28],
 ['nadym', 'Надым', 72.5166667, 65.5333333, -24, -15],
 ['tarko', 'Тарко-Сале', 77.774574, 64.916114, 22, -2],
 ['muravlenko', 'Муравленко', 74.52301025390625, 63.7897654037041, -25, -5],
 ['gubkinsky', 'Губкинский', 76.50260925292969, 64.43400309088979, 28, 19],
];
const cities = raw.map(([id, name, lon, lat, dx, dy]) => {const [x, y] = point([lon, lat]); return {id, name, lon, lat, x, y, dx, dy};});
const graticule = [];
for (let lon = 60; lon <= 90; lon += 5) graticule.push(line(Array.from({length: 141}, (_, i) => [lon, 61 + i / 10])));
for (let lat = 64; lat <= 74; lat += 2) graticule.push(line(Array.from({length: 321}, (_, i) => [58 + i / 10, lat])));
